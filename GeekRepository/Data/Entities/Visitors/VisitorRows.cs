namespace GeekRepository.Data.Entities.Visitors;

// The rows of the geek_visitors schema (Migrations/Sql/0042_geek_visitors_schema.sql). Storage
// types: they exist only in GeekRepository. GeekAPI sees the records in
// GeekApplication.Models.Visitors, which VisitorRowMapping builds from these rows and writes back
// into them, so a nested object of a record is a group of columns here and each field is one
// column and one contract. Every column is the snake_case of its property name
// (VisitorsDbContext applies that rule), so the script and this file can be read side by side.

/// <summary>geek_visitors.visitors: one browser, by the persistent visitor UUID.</summary>
public sealed class VisitorRow
{
    public Guid Id { get; set; }
    public DateTime FirstSeenAt { get; set; }
    public DateTime LastSeenAt { get; set; }
    public int SessionCount { get; set; }
    public string? IdentityFirstName { get; set; }
    public string? IdentityLastName { get; set; }
    public string? IdentityEmail { get; set; }
    public string? IdentityPhone { get; set; }
    public string? IdentitySource { get; set; }
    public DateTime? IdentifiedAt { get; set; }
    /// <summary>Optimistic concurrency token, bumped on every write.</summary>
    public int Version { get; set; }
}

